#!/usr/bin/env python3
"""Write prompts/PROMPTS.md: every rubric, criterion and question wording that run_raters.py sends (single source of truth)."""
import json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
src = (HERE / "run_raters.py").read_text().replace('if __name__ == "__main__":\n    main()', "")
ns = {"__file__": str(HERE / "run_raters.py")}
exec(compile(src, "run_raters", "exec"), ns)
def block(title, d): return f"### {title}\n\n" + "\n".join(f"- **{k}**: {v}" for k, v in d.items()) + "\n"
ex = json.loads((HERE / "examples/fidelity_examples.json").read_text())
out = ["# Prompts sent to the decision models", "", "Generated by `dump_prompts.py` from `run_raters.py`. The models get this text plus the per-EVD inputs shown in `prompts/rendered/`.", "",
       "## Relevancy: review criterion (shown after the EVD's review question(s))", "", ns["CRITERION"], "",
       "Question: *Is this EVD relevant to the REVIEW QUESTION(S) and the REVIEW CRITERION, and worth learning? Yes means Relevant; No means Irrelevant.*", "",
       "## Fidelity (version 3, used in run r1)", "", "Question: *Is the gist of the EVD statement in the quoted text? Choose Met when its main finding is there; missing specific numbers or details do not matter.*", "",
       block("Options", ns["FIDELITY_V2"]), "Worked examples (EVD 1-3, JP's Fidelity ratings; EVD 1-3 are skipped for this task):", ""]
for e in ex["examples"]: out += [f"- EVD {e['evd']}: {e['evd_statement']} -> **{e['label']}**. {e['why']}"]
out += ["", "## Grounding: Quote", "", "Question: *Does the screenshot shown with the quote correctly show the quoted text?*", "", block("Options", ns["QUOTE"]),
        "## Grounding: Table/Figure", "", "Question: *Does the evidence page show the correct table or figure for the EVD statement's numbers?*", "", block("Options", ns["TABLE"]),
        "Rule (JP, 2026-11-23): if no table/figure screenshot is shown the answer is Missing and no model is called.", ""]
(HERE / "prompts").mkdir(exist_ok=True)
(HERE / "prompts/PROMPTS.md").write_text("\n".join(out)); print("prompts/PROMPTS.md written")
